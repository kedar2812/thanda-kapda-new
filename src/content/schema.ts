/**
 * How the dashboard presents the content for editing: pages, their sections
 * and a label and hint for every field. Field keys are dot paths relative to
 * the section's path. Section ids match the data-cms attributes on the site,
 * so "Edit" in the live preview opens the right section.
 *
 * tests/schema-check (dashboard) verifies that every field here exists in the
 * defaults and that every text and photo in the defaults has a field.
 */
import type { Field, GroupField, ImageField, ListField, NumberField, PageGroup, Section, TextField, ToggleField, UrlField } from "./types";

const text = (label: string, extra: Partial<TextField> = {}): TextField => ({ kind: "text", label, ...extra });
const long = (label: string, extra: Partial<TextField> = {}): TextField => text(label, { long: true, ...extra });
const rich = (label: string, extra: Partial<TextField> = {}): TextField =>
  text(label, { rich: true, hint: "Wrap words in *asterisks* for the accent style. Press Enter for a new line.", ...extra });
const url = (label: string, extra: Partial<UrlField> = {}): UrlField => ({ kind: "url", label, ...extra });
const num = (label: string, extra: Partial<NumberField> = {}): NumberField => ({ kind: "number", label, ...extra });
const toggle = (label: string, hint?: string): ToggleField => ({ kind: "toggle", label, hint });
const img = (label: string, aspect?: string, hint?: string): ImageField => ({ kind: "image", label, aspect, hint });
const icon = (label = "Icon") => ({ kind: "icon", label }) as const;
const list = (label: string, noun: string, item: Field, extra: Partial<ListField> = {}): ListField => ({ kind: "list", label, noun, item, ...extra });
const group = (label: string, fields: Record<string, Field>, extra: Partial<GroupField> = {}): GroupField => ({ kind: "group", label, fields, ...extra });
const words = (label: string, noun: string, extra: Partial<ListField> = {}) => list(label, noun, text(noun), extra);
const seal = (label = "Seal text") => text(label, { hint: "Runs around a circle. End with “ · ” so the ends meet neatly.", max: 60 });

const iconCard = (noun: string, extra: Partial<ListField> = {}) =>
  list(`${noun}s`, noun.toLowerCase(), group(noun, { icon: icon(), title: text("Title"), text: long("Text") }), { titleKey: "title", ...extra });

const header = (id: string, label: string, root: string, previewPath: string): Section => ({
  id,
  label,
  path: root,
  preview: previewPath,
  fields: { eyebrow: text("Small heading"), title: rich("Page title"), intro: long("Introduction") },
});

